                            modifier = Modifier.size(22.dp)
                        )
                        Text(
                            text = "100% On-Device Data Storage",
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.onSurface
                        )
                    }
                    Text(
                        text = "• Notes and Expenses are stored strictly in an encrypted on-device SQLite / Room database.\n• Calculation histories and generated passwords exist solely in volatile device memory and are never persisted or shared.\n• Your financial entries, notes, and records never leave your physical device.",
